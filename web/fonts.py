"""Build complete Unicode-ranged font shards; only asset maintainers need Python.

Requirements: fonttools[woff]==4.61.1. Run from the repository root.
The core character list is fixed input; all remaining cmap entries are retained.
"""

from pathlib import Path
from copy import deepcopy
import hashlib
import json
import logging
import sys
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "assets/fonts/zhuque.woff2"
DESTINATION = ROOT / "assets/fonts/zhuque"
logging.getLogger("fontTools").setLevel(logging.ERROR)


def unicode_ranges(points):
    runs = []
    for point in sorted(points):
        if runs and runs[-1][1] + 1 == point:
            runs[-1][1] = point
        else:
            runs.append([point, point])
    return ",".join(f"U+{a:X}" if a == b else f"U+{a:X}-{b:X}" for a, b in runs)


def main():
    DESTINATION.mkdir(parents=True, exist_ok=True)
    master = TTFont(SOURCE, lazy=False, recalcTimestamp=False)
    master.ensureDecompiled(recurse=True)
    coverage = set(master.getBestCmap())
    core = set(map(ord, (ROOT / "assets/fonts/zhuque-core.txt").read_text())) & coverage
    groups = {"core": core}
    for point in sorted(coverage - core):
        groups.setdefault(f"u{point // 256:04x}", set()).add(point)
    faces, files, manifest = [], [], []
    for name, points in groups.items():
        font = deepcopy(master)
        options = subset.Options()
        options.layout_features = ["*"]
        options.recalc_timestamp = False
        worker = subset.Subsetter(options=options)
        worker.populate(unicodes=points)
        worker.subset(font)
        temporary = DESTINATION / f"{name}.woff2"
        font.save(temporary)
        font.close()
        checksum = hashlib.sha256(temporary.read_bytes()).hexdigest()[:12]
        filename = f"{name}-{checksum}.woff2"
        temporary.replace(DESTINATION / filename)
        face = f'@font-face{{font-family:Zhuque;src:url({filename}) format("woff2");font-weight:400;font-display:swap;unicode-range:{unicode_ranges(points)}}}'
        faces.append(face)
        relative = f"assets/fonts/zhuque/{filename}"
        files.append(f'    ("{relative}", include_bytes!("../../../{relative}")),')
        manifest.append({"file": filename, "codepoints": sorted(points)})
        print(f"{name}: {len(points)} characters", flush=True)
    (DESTINATION / "subsets.css").write_text("\n".join(faces) + "\n")
    (DESTINATION / "coverage.json").write_text(json.dumps(manifest, separators=(",", ":")) + "\n")
    generated = "// Generated by web/fonts.py; do not edit.\nconst FONT_SUBSETS: &[(&str, &[u8])] = &[\n" + "\n".join(files) + "\n];\n"
    (ROOT / "crates/blog/resources/font-subsets.rs").write_text(generated)
    print(f"Generated {len(groups)} font shards covering all {len(coverage)} characters")


def verify():
    original = TTFont(SOURCE)
    expected = original.getBestCmap()
    manifest = json.loads((DESTINATION / "coverage.json").read_text())
    css = (DESTINATION / "subsets.css").read_text()
    observed = set()
    for entry in manifest:
        path = DESTINATION / entry["file"]
        assert path.name in css, f"Missing CSS declaration for {path.name}"
        assert hashlib.sha256(path.read_bytes()).hexdigest()[:12] in path.name
        font = TTFont(path)
        actual = font.getBestCmap()
        assert set(actual) == set(entry["codepoints"]), f"Incorrect coverage in {path.name}"
        assert not observed.intersection(actual), f"Overlapping character ranges in {path.name}"
        for point, glyph in actual.items():
            assert original["hmtx"].metrics[expected[point]][0] == font["hmtx"].metrics[glyph][0], f"Changed glyph width: {point:X}"
        assert font["hhea"].ascent == original["hhea"].ascent
        assert font["hhea"].descent == original["hhea"].descent
        observed.update(actual)
        font.close()
    assert observed == set(expected), "Font shards must retain the complete original character set"
    print(f"Verified {len(observed)} characters and unchanged advance widths across {len(manifest)} shards")


if __name__ == "__main__":
    if sys.argv[1:] == ["--check"]:
        verify()
    else:
        main()
