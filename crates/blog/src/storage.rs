//! Filesystem ownership: a build lock, atomic source writes, and staged publication.
use anyhow::{Context, Result, bail};
use std::{
    fs,
    path::{Path, PathBuf},
};

const OUTPUT_MARKER: &str = "blog-output-v1\n";

/// Dropping the file releases the process-wide advisory lock.
pub(crate) struct BuildLock {
    _file: fs::File,
}

impl BuildLock {
    pub fn acquire(root: &Path) -> Result<Self> {
        fs::create_dir_all(root.join(".blog"))?;
        let file = fs::OpenOptions::new()
            .create(true)
            .truncate(false)
            .read(true)
            .write(true)
            .open(root.join(".blog/build.lock"))?;
        fs2::FileExt::lock_exclusive(&file)?;
        Ok(Self { _file: file })
    }
}

/// Every artifact is written into a temporary directory before publication.
pub(crate) struct Publication {
    stage: tempfile::TempDir,
    output: PathBuf,
    scratch: PathBuf,
}

impl Publication {
    pub fn validate(output: &Path) -> Result<()> {
        if output.exists() {
            if output.is_symlink() || !output.is_dir() {
                bail!(
                    "The output path must be a separate directory: {}",
                    output.display()
                );
            }
            if fs::read_to_string(output.join(".blog-generated"))
                .ok()
                .as_deref()
                != Some(OUTPUT_MARKER)
                && fs::read_dir(output)?.next().is_some()
            {
                bail!(
                    "The output directory contains files not generated by this framework; choose an empty directory: {}",
                    output.display()
                );
            }
        }
        Ok(())
    }

    pub fn new(root: &Path, output: &str) -> Result<Self> {
        let output = root.join(output);
        Self::validate(&output)?;
        let scratch = root.join(".blog");
        Ok(Self {
            stage: tempfile::tempdir_in(&scratch)?,
            output,
            scratch,
        })
    }

    pub fn write(&self, relative: impl AsRef<Path>, value: impl AsRef<[u8]>) -> Result<()> {
        let path = self.stage.path().join(relative);
        fs::create_dir_all(path.parent().context("The path has no parent directory")?)?;
        fs::write(path, value)?;
        Ok(())
    }

    pub fn copy_static(&self, from: &Path) -> Result<()> {
        if !from.exists() {
            return Ok(());
        }
        for entry in walkdir::WalkDir::new(from) {
            let entry = entry?;
            if entry.file_type().is_symlink() {
                bail!("Symbolic links are not supported in static assets");
            }
            if entry.file_type().is_file() {
                let path = self.stage.path().join(entry.path().strip_prefix(from)?);
                fs::create_dir_all(path.parent().context("The path has no parent directory")?)?;
                fs::copy(entry.path(), path)?;
            }
        }
        Ok(())
    }

    /// A failed rename restores the previous output; dropping an unfinished stage
    /// only removes the temporary artifacts.
    pub fn commit(self) -> Result<()> {
        self.write(".blog-generated", OUTPUT_MARKER)?;
        fs::create_dir_all(
            self.output
                .parent()
                .context("The path has no parent directory")?,
        )?;
        let backup = tempfile::tempdir_in(&self.scratch)?;
        let previous = backup.path().join("previous");
        if self.output.exists() {
            fs::rename(&self.output, &previous)?;
        }
        if let Err(error) = fs::rename(self.stage.path(), &self.output) {
            if previous.exists()
                && let Err(restore) = fs::rename(&previous, &self.output)
            {
                let recovery = backup.keep();
                bail!(
                    "Publication failed: {error}; restoring the previous output failed: {restore}; the previous output is preserved at {}",
                    recovery.join("previous").display()
                );
            }
            return Err(error.into());
        }
        Ok(())
    }
}

/// Only missing overrides use the bundled default; invalid files remain errors.
pub(crate) fn read_override(root: &Path, relative: &str, fallback: &[u8]) -> Result<Vec<u8>> {
    match fs::read(root.join(relative)) {
        Ok(bytes) => Ok(bytes),
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok(fallback.to_vec()),
        Err(error) => Err(error).with_context(|| format!("Reading {relative}")),
    }
}

pub(crate) fn read_text_override(root: &Path, relative: &str, fallback: &str) -> Result<String> {
    String::from_utf8(read_override(root, relative, fallback.as_bytes())?)
        .with_context(|| format!("{relative} must be UTF-8"))
}

pub(crate) fn atomic_write(path: &Path, bytes: &[u8]) -> Result<()> {
    use std::io::Write;
    let mut file = tempfile::NamedTempFile::new_in(
        path.parent().context("The path has no parent directory")?,
    )?;
    file.write_all(bytes)?;
    file.as_file().sync_all()?;
    file.persist(path).map_err(|e| e.error)?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn abandoned_publication_preserves_the_previous_site() -> Result<()> {
        let root = tempfile::tempdir()?;
        let _lock = BuildLock::acquire(root.path())?;
        let initial = Publication::new(root.path(), "_site")?;
        initial.write("index.html", "previous site")?;
        initial.commit()?;

        let failed = Publication::new(root.path(), "_site")?;
        failed.write("index.html", "partial replacement")?;
        assert!(failed.write("index.html/child", "cannot publish").is_err());
        drop(failed);

        assert_eq!(
            fs::read_to_string(root.path().join("_site/index.html"))?,
            "previous site"
        );
        Ok(())
    }

    #[test]
    fn only_absent_overrides_use_the_default() -> Result<()> {
        let root = tempfile::tempdir()?;
        assert_eq!(
            read_override(root.path(), "theme.css", b"default")?,
            b"default"
        );
        fs::create_dir(root.path().join("theme.css"))?;
        let error = read_override(root.path(), "theme.css", b"default").unwrap_err();
        assert!(format!("{error:#}").contains("theme.css"));
        Ok(())
    }
}
