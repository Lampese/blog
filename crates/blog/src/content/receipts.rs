//! Shorten only registered, literal clipboard receipts using Typst's syntax tree.
use super::Include;
use crate::storage::atomic_write;
use anyhow::Result;
use blog_ranges::RangeReference;
use std::{collections::BTreeMap, fs, path::Path};

pub(crate) fn compact_receipts(
    path: &Path,
    resolves: impl Fn(&RangeReference) -> bool,
) -> Result<()> {
    use typst_syntax::ast::{self, Arg, DictItem, Expr};
    fn literal_reference(node: &typst_syntax::SyntaxNode) -> Option<RangeReference> {
        let call = node.cast::<ast::FuncCall>()?;
        if !matches!(call.callee(), Expr::Ident(name) if name.get() == "excerpt") {
            return None;
        }
        let mut args = call.args().items();
        let Arg::Pos(Expr::Dict(dict)) = args.next()? else {
            return None;
        };
        if args.next().is_some() {
            return None;
        }
        let mut fields = BTreeMap::new();
        for item in dict.items() {
            let DictItem::Named(item) = item else {
                return None;
            };
            fields.insert(item.name().get().as_str(), item.expr());
        }
        if fields.len() != 4 || !matches!(fields.get("schema"), Some(Expr::Int(n)) if n.get() == 1)
        {
            return None;
        }
        let Expr::Str(article) = fields.get("article")? else {
            return None;
        };
        let Expr::Str(range) = fields.get("range")? else {
            return None;
        };
        let Expr::Dict(receipt) = fields.get("receipt")? else {
            return None;
        };
        let mut receipt_fields = BTreeMap::new();
        for item in receipt.items() {
            let DictItem::Named(item) = item else {
                return None;
            };
            receipt_fields.insert(item.name().get().as_str(), item.expr());
        }
        if receipt_fields.len() != 3
            || !matches!(receipt_fields.get("start"), Some(Expr::Int(n)) if n.get() >= 0)
            || !matches!(receipt_fields.get("end"), Some(Expr::Int(n)) if n.get() > 0)
            || !matches!(receipt_fields.get("seed"), Some(Expr::Str(_)))
        {
            return None;
        }
        Some(RangeReference {
            schema: 1,
            article: article.get().to_string(),
            range: range.get().to_string(),
        })
    }
    fn walk(
        node: &typst_syntax::SyntaxNode,
        offset: usize,
        edits: &mut Vec<(std::ops::Range<usize>, String)>,
        resolves: &impl Fn(&RangeReference) -> bool,
    ) {
        // Only the exact literal shape generated by the clipboard is shortened.
        // Computed expressions and extended metadata retain their original source.
        if let Some(reference) = literal_reference(node)
            && resolves(&reference)
        {
            let code = Include {
                reference,
                receipt: None,
            }
            .code();
            edits.push((
                offset..offset + node.len(),
                code.trim_start_matches('#').to_owned(),
            ));
            return;
        }
        let mut next = offset;
        for child in node.children() {
            walk(child, next, edits, resolves);
            next += child.len();
        }
    }
    let source = fs::read_to_string(path)?;
    let parsed = typst_syntax::parse(&source);
    let mut edits = Vec::new();
    walk(&parsed, 0, &mut edits, &resolves);
    if !edits.is_empty() {
        let mut next = source;
        for (range, replacement) in edits.into_iter().rev() {
            next.replace_range(range, &replacement);
        }
        atomic_write(path, next.as_bytes())?;
    }
    Ok(())
}
